    private void btnLogIn(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogIn
        // TODO add your handling code here:
        String Username, Password;
        
        Username = TFUsername.getText();
        Password= TFPassword.getText();
        int Usertype= UserType.getSelectedIndex();
        
        List<String> errors = new ArrayList<>();

        lblError.setText(""); 
        lblError2.setText("");
        lblError3.setText("");
        lblError.setForeground(java.awt.Color.BLACK);
        lblError2.setForeground(java.awt.Color.BLACK);
        lblError3.setForeground(java.awt.Color.BLACK);
        TFUsername.setForeground(java.awt.Color.BLACK);
        TFPassword.setForeground(java.awt.Color.BLACK);
        UserType.setForeground(java.awt.Color.BLACK);

        try{
            
// 1. Check for empty fields
    if (Password.isEmpty() || Password.equals("Enter Password") || Username.isEmpty() || Username.equals("Enter Username")) {
        errors.add("Please enter username/password");
    }

    // 2. Check for missing user type selection
    if (Usertype == 0) {
        errors.add("Please select a user type!");
    }

    // 3. Check for specific Lecturer credentials
    if (Usertype == 1 && (!Password.equals("Lecturer") || !Username.equals("Lecturer"))) {
        errors.add("Lecturer not found");
    }
    
    if (Usertype == 2 && (!Password.equals("Admin") || !Username.equals("Admin"))) {
        errors.add("Admin not found");
    }
    if (Usertype == 3 && (!Password.equals("Authorities") || !Username.equals("Authorities"))) {
        errors.add("Authorities not found");
    }

    // 4. If the list has ANY messages, throw our custom exception containing the whole list
    if (!errors.isEmpty()) {
        throw new FormValidationException(errors);
    }

    // Success Path: Code here runs only if NO exceptions were triggered
    this.dispose();
    frame2 dashboard = new frame2();
    dashboard.setVisible(true);

} catch (FormValidationException ex) {
    // 5. Error Path: Inspect the list of errors gathered during execution
    List<String> errorList = ex.getErrorList();

    if (errorList.contains("Please select a user type!")) {
        UserType.setForeground(java.awt.Color.RED);
        lblError2.setText("Please select a user type!"); 
        lblError2.setForeground(java.awt.Color.RED);
    }

    if (errorList.contains("Please enter username/password")) {
        lblError.setText("Please enter username/password"); 
        lblError.setForeground(java.awt.Color.RED);
        TFUsername.setForeground(java.awt.Color.RED);
        TFPassword.setForeground(java.awt.Color.RED);
    }    

    if (errorList.contains("Lecturer not found")) {
        lblError3.setText("Lecturer not found"); 
        lblError3.setForeground(java.awt.Color.RED);
        TFUsername.setForeground(java.awt.Color.RED);
        TFPassword.setForeground(java.awt.Color.RED);
        
   
    }
    if (errorList.contains("Admin not found")) {
        lblError3.setText("Admin not found"); 
        lblError3.setForeground(java.awt.Color.RED);
        TFUsername.setForeground(java.awt.Color.RED);
        TFPassword.setForeground(java.awt.Color.RED);
        
   
    }
    if (errorList.contains("Authorities not found")) {
        lblError3.setText("Authorities not found"); 
        lblError3.setForeground(java.awt.Color.RED);
        TFUsername.setForeground(java.awt.Color.RED);
        TFPassword.setForeground(java.awt.Color.RED);
        
   
    }
}
    
    }//GEN-LAST:event_btnLogIn

    private void formWindowActivated(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowActivated
        // TODO add your handling code here:
        
        javax.swing.ImageIcon[] images = {
    new javax.swing.ImageIcon(getClass().getResource("/image1.jpg")), // Index 0
    new javax.swing.ImageIcon(getClass().getResource("/image2.jpg")), // Index 1
    new javax.swing.ImageIcon(getClass().getResource("/image3.jpg"))  // Index 2
};

// 2. Set index 0 as the starting image layout
if (images.length > 0) {
    lblImage.setIcon(images[0]);
}

// 3. The Timer loops through these array indices every 6 seconds
javax.swing.Timer imageTimer = new javax.swing.Timer(6000, new java.awt.event.ActionListener() {
    private int currentIndex = 0; // Starts at index 0

    @Override
    public void actionPerformed(java.awt.event.ActionEvent e) {
        // Increment index, then reset to 0 once it passes the last item in the array
        currentIndex = (currentIndex + 1) % images.length;
        
        // Apply the new image based on the calculated index
        lblImage.setIcon(images[currentIndex]);
    }
});

// 4. Start the timer execution loop
imageTimer.start();
    }//GEN-LAST:event_formWindowActivated


