    private void btnLogIn(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogIn
        // TODO add your handling code here:
            try {

        String username = TFUsername.getText().trim();
        String password = TFPassword.getText();

        // Validate fields
        if (username.isEmpty() || password.isEmpty()) {
            throw new IllegalArgumentException(
                "Enter your username and password."
            );
        }

        // Validate user type
        if (UserType.getSelectedIndex() == 0) {
            throw new IllegalArgumentException(
                "Please select your user type."
            );
        }

        // Authenticate user
        User loggedInUser = DataStore.login(
            username, password
        );

        if (loggedInUser == null) {
            throw new IllegalArgumentException(
                "Incorrect username or password."
            );
        }

        // Match dropdown with account role
        String selectedRole = switch (UserType.getSelectedItem().toString()) {
            case "Admin" -> "ADMIN";
            case "Lecturer" -> "LECTURER";
            case "Authority" -> "AUTHORITY";
            default -> "";
            };

        if (!loggedInUser.getRole()
                .equalsIgnoreCase(selectedRole)) {

            throw new IllegalArgumentException(
                "Selected role does not match your account."
            );
        }

        // Open correct dashboard
        javax.swing.JFrame dashboard;

        switch (loggedInUser.getRole().toUpperCase()) {

            case "ADMIN" -> 
                dashboard = new AdminDashboard(username);

            case "LECTURER" ->
                dashboard = new LecturerDashboard(username);

            case "AUTHORITY" ->
                dashboard = new AuthorityDashboard(username);

            default ->
                throw new IllegalArgumentException(
                    "Invalid user role."
                );
        }

        dashboard.setVisible(true);

        this.dispose();

    } catch (IllegalArgumentException ex) {

        JOptionPane.showMessageDialog(
            this,
            ex.getMessage(),
            "Login Error",
            JOptionPane.ERROR_MESSAGE
        );

    } catch (Exception ex) {

        logger.log(
            java.util.logging.Level.SEVERE,
            "Login error",
            ex
        );

        JOptionPane.showMessageDialog(
            this,
            "An unexpected error occurred.",
            "System Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnLogIn

    private void formWindowActivated(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowActivated
   if (lblImage.getClientProperty("myTimer") == null) {

        javax.swing.ImageIcon[] images = {
            new javax.swing.ImageIcon(getClass().getResource("/image1.jpg")), 
            new javax.swing.ImageIcon(getClass().getResource("/image2.jpg")), 
            new javax.swing.ImageIcon(getClass().getResource("/image3.jpg"))  
        };

        if (images.length > 0) {
            lblImage.setIcon(images[0]);
        }

       
        int[] currentIndex = { 0 }; 
        
       
        lblImage.putClientProperty("myIndex", currentIndex);

        
        javax.swing.Timer imageTimer = new javax.swing.Timer(6000, e -> {
            
            int[] idx = (int[]) lblImage.getClientProperty("myIndex");
            
            idx[0] = (idx[0] + 1) % images.length;
            lblImage.setIcon(images[idx[0]]);
        });

        imageTimer.start();
        
        
        lblImage.putClientProperty("myTimer", imageTimer);
    }
    }//GEN-LAST:event_formWindowActivated

