private void loadCputBanner() {

    java.net.URL bannerURL =
            getClass().getResource("/cput.jpg");

    // Check whether the image exists
    if (bannerURL == null) {

        System.out.println(
            "ERROR: cput.jpg was not found in the project."
        );

        lblCputjpg.setText("CPUT Banner Missing");

        return;
    }

    // Load the image
    javax.swing.ImageIcon banner =
            new javax.swing.ImageIcon(bannerURL);

    // Check that the image loaded correctly
    if (banner.getIconWidth() <= 0) {

        System.out.println("ERROR: Invalid CPUT banner image.");

        return;
    }

    // Display banner
    lblCputjpg.setIcon(banner);
    lblCputjpg.setText("");

    // Use the image's original width
    lblCputjpg.setPreferredSize(
        new java.awt.Dimension(
            banner.getIconWidth(),
            155
        )
    );

    lblCputjpg.revalidate();
    lblCputjpg.repaint();
}


